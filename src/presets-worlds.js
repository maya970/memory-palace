import { approach, halls, heightOf, land } from './presets-site.js';

function site(opts) {
  const g = grid();
  land(g, {
    x0: -40, z0: -36, x1: 40, z1: 40,
    kind: opts.kind,
    top: opts.top,
    fill: opts.fill,
    waterY: opts.waterY,
  });
  const plateau = opts.plateau ?? heightOf(0, -6, opts.kind);
  const built = halls(g, {
    ox: opts.ox ?? -12,
    oz: opts.oz ?? -18,
    cols: 5,
    rows: 5,
    y: plateau,
    wall: opts.wall,
    floor: opts.floor,
    roof: opts.roof,
    fill: opts.fill,
    accent: opts.accent,
    wallH: opts.wallH || 5,
    inner: 4,
    style: opts.style,
    skipWindows: true,
  });
  const tread = opts.tread || 'cobblestone';
  const pathY = approach(g, built.doorX, built.doorZ, built.floorY, 38, opts.kind, tread, opts.fill, true);
  if (opts.kind === 'water') {
    for (let z = built.doorZ; z <= 40; z += 1) {
      g.box(-2, built.floorY, z, 2, built.floorY, z, tread);
      g.box(-2, (opts.waterY || 0) - 1, z, -2, built.floorY - 1, z, opts.fill);
      g.box(2, (opts.waterY || 0) - 1, z, 2, built.floorY - 1, z, opts.fill);
    }
  }
  opts.dress?.(g, plateau, built);
  const spawnY = (opts.kind === 'water' ? built.floorY : pathY) + 1;
  return finish(
    opts.id,
    opts.name,
    opts.lead,
    g,
    { x: 0.5, y: spawnY, z: 38.5, yaw: Math.PI, pitch: -0.08 },
    opts.credit,
    opts.country,
  );
}

