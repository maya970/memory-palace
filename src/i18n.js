for (const [id, pack] of Object.entries(extraKeys)) Object.assign(packs[id], pack);
for (const pack of Object.values(packs)) pack.accountFile ||= packs.en.accountFile;

let current = detect();
const listeners = new Set();

function detect() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && (packs[saved] || saved === 'zh' || saved === 'en')) return saved;
  } catch { /* private mode */ }
  const nav = (typeof navigator === 'undefined' ? 'zh' : navigator.language || 'zh').toLowerCase();
  const hit = LANGS.find((item) => nav === item.id || nav.startsWith(`${item.id}-`));
  return hit?.id || 'zh';
}

export function t(key, vars) {
  const pack = packs[current] || packs.zh;
  let text = pack[key] ?? packs.en[key] ?? packs.zh[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function onLang(listener) {
  listeners.add(listener);
}

export function applyI18n() {
  if (typeof document === 'undefined') return;
  const lang = LANGS.find((item) => item.id === current) || LANGS[0];
  document.documentElement.lang = current;
  document.documentElement.dir = lang.dir;
  document.title = t('brand');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  document.querySelectorAll('[data-lang]').forEach((select) => {
    if (!select.dataset.bound) {
      select.innerHTML = LANGS.map((item) => `<option value="${item.id}">${item.name}</option>`).join('');
      select.dataset.bound = '1';
      select.addEventListener('change', () => setLang(select.value));
    }
    select.value = current;
  });
  listeners.forEach((listener) => listener());
}

export function setLang(id) {
  if (!packs[id]) return;
  current = id;
  try { localStorage.setItem(KEY, id); } catch { /* ignore */ }
  applyI18n();
}
